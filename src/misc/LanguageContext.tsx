const translations = { id, en } as const;

export function getCurrentLanguage(): AppLanguage {
  try {
    return DatabaseManager.getSync('language') === 'en' ? 'en' : 'id';
  } catch {
    return 'id';
  }
}

export async function setAppLanguage(lang: AppLanguage): Promise<void> {
  moment.locale(lang);
  await DatabaseManager.set('language', lang);
}

function formatMessage(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) =>
    params[k] !== undefined && params[k] !== null ? String(params[k]) : `{${k}}`,
  );
}

export function tSync(
  key: TranslationKey,
  params?: Record<string, string | number>,
  langOverride?: AppLanguage,
): string {
  const lang = langOverride ?? getCurrentLanguage();
  const dict = translations[lang] ?? translations.id;
  const template = dict[key] ?? translations.id[key] ?? key;
  return formatMessage(template, params);
}

interface LanguageContextValue {
  language: AppLanguage;
  setLanguage: (lang: AppLanguage) => Promise<void>;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  language: 'id',
  setLanguage: setAppLanguage,
  t: (key, params) => tSync(key, params, 'id'),
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    const initial = getCurrentLanguage();
    moment.locale(initial);
    return initial;
  });

  useEffect(() => {
    const current = getCurrentLanguage();
    moment.locale(current);
    setLanguageState(current);

    const listener = DatabaseManager.listenOnValueChanged(key => {
      if (key === 'language') {
        const next = getCurrentLanguage();
        moment.locale(next);
        setLanguageState(next);
      }
    });
    return () => listener.remove();
  }, []);

  const setLanguage = useCallback(async (lang: AppLanguage) => {
    moment.locale(lang);
    setLanguageState(lang);
    await DatabaseManager.set('language', lang);
  }, []);

  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) => {
      return tSync(key, params, language);
    },
    [language],
  );

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t,
    }),
    [language, setLanguage, t],
  );

  return <LanguageContext value={value}>{children}</LanguageContext>;
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
